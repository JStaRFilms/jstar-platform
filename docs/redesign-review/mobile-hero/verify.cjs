const { chromium } = require('C:/Users/johno/AppData/Local/npm-cache/_npx/e41f203b7505f1fb/node_modules/playwright');
const path = require('node:path');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const dir = __dirname;
const url = process.env.REDESIGN_URL || 'http://127.0.0.1:5798/redesign';
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const errors = [];
  const context = await browser.newContext({ viewport: { width: 360, height: 760 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
  const page = await context.newPage();
  page.on('pageerror', e => errors.push(e.message));
  try {
    await page.goto(url, { waitUntil: 'load', timeout: 90000 });
    await page.waitForFunction(() => Number(document.querySelector('[data-denominator]')?.dataset.denominator) > 0);
    await page.addStyleTag({ content: 'nextjs-portal { display: none !important; }' });
    const metrics = () => page.evaluate(() => {
      const section = document.querySelector('[data-denominator]');
      const stage = section.querySelector('[class*="stage"]');
      const film = stage.querySelector('video');
      const box = element => { const r = element.getBoundingClientRect(); return { x: Math.round(r.x), y: Math.round(r.y), width: Math.round(r.width), height: Math.round(r.height) }; };
      return { scrollY, innerHeight, stage: box(stage), film: box(film), frame: box(film.parentElement), denominator: Number(section.dataset.denominator), screen: document.querySelector('[data-screening]')?.dataset.screening, words: [...document.querySelectorAll('[class*="mobileLine"]')].filter(x => getComputedStyle(x).display !== 'none').map(x => ({ text: x.firstChild.textContent, box: box(x) })), copy: box(stage.querySelector('[class*="description"]')), active: document.activeElement?.tagName };
    });
    const travel = async progress => { await page.evaluate(progress => { const s = document.querySelector('[data-denominator]'); window.scrollTo({top: window.scrollY + s.getBoundingClientRect().top + progress * Number(s.dataset.denominator), behavior:'instant'}); }, progress); await page.waitForTimeout(2000); };
    const results = { baseline: await metrics(), errors };
    await page.screenshot({ path: path.join(dir, 'opening.png'), scale: 'css' });
    await travel(.28);
    results.entry = await metrics();
    await page.screenshot({ path: path.join(dir, 'mid-entry.png'), scale: 'css' });
    await travel(.85);
    results.fullscreen = await metrics();
    await page.screenshot({ path: path.join(dir, 'fullscreen.png'), scale: 'css' });
    await page.setViewportSize({ width: 360, height: 680 });
    await pause(900);
    results.shortViewport = await metrics();
    assert.ok(results.shortViewport.frame.height >= 680, 'film leaves a strip');
    await page.setViewportSize({ width: 360, height: 760 });
    await travel(1.8);
    results.tablet = await metrics();
    await page.screenshot({ path: path.join(dir, 'tablet.png'), scale: 'css' });
    await travel(0);
    await page.waitForTimeout(1600);
    results.returned = await metrics();
    await page.screenshot({ path: path.join(dir, 'returned.png'), scale: 'css' });
    await page.waitForTimeout(4200);
    results.idle = await page.evaluate(() => ({ active: [...document.querySelectorAll('[data-scrambling="true"]')].map(x => x.textContent), wave: [...document.querySelectorAll('[class*="mobileCopy"] > span')].map(x => x.style.transform) }));
    await page.evaluate(() => window.scrollTo({ top: 180, behavior: 'instant' }));
    await pause(100);
    results.interrupted = await page.evaluate(() => ({ active: document.querySelectorAll('[data-scrambling="true"]').length, wave: [...document.querySelectorAll('[class*="mobileCopy"] > span')].map(x => x.style.transform) }));
    await page.setViewportSize({ width: 320, height: 560 });
    await travel(0);
    results.narrowShort = await metrics();
    await page.screenshot({ path: path.join(dir, 'narrow-short.png'), scale: 'css' });
    await page.setViewportSize({ width: 760, height: 360 });
    results.landscape = await metrics();
    assert.ok(results.landscape.copy.y + results.landscape.copy.height < 310, 'landscape copy collides with work link');
    await page.screenshot({ path: path.join(dir, 'landscape.png'), scale: 'css' });
    fs.writeFileSync(path.join(dir, 'metrics.json'), JSON.stringify(results, null, 2));
    console.log(JSON.stringify(results));
  } finally { await context.close(); await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
